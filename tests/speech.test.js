test('темп: рекламний текст із короткими рядками', () => {
    const t = 'Кожен день вимагає готовності. Щоб змінюватися й діяти.\nМи шукаємо власну опору в русі.\nТому спортивний одяг стає стилем життя.\nМи вибираємо спорт, задля.\nБалансу. Фокусу. Стійкості.\nЗаряд, що залишається з тобою на весь день.\nСпортивний одяг як лайфстайл.\nUnder Armour. Нова база сучасного гардероба.';
    const sec = S.analyze(t).seconds;
    assert.ok(sec > 24.5 && sec < 26.5, `${sec}`); // раніше калькулятор показував 26 сек
    // новий рядок після крапки не додає паузи, порожній рядок між абзацами — додає
    assert.strictEqual(S.analyze('Раз. Два.').seconds, S.analyze('Раз.\nДва.').seconds);
    assert.ok(S.analyze('Раз.\n\nДва.').seconds > S.analyze('Раз.\nДва.').seconds);
});

